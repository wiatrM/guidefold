import {chromium,expect} from '@playwright/test';
import fs from 'node:fs/promises';
const browser=await chromium.launch();const page=await browser.newPage({viewport:{width:390,height:720}});
await page.goto('http://127.0.0.1:4330/proposals',{waitUntil:'networkidle'});
await page.locator('main [aria-busy=true]').waitFor({state:'hidden'});
const menu=page.locator('details').filter({has:page.locator('summary').filter({hasText:'Navigate ·'})});
await expect(menu).not.toHaveAttribute('open','');
const summary=menu.locator('summary');await summary.focus();await page.keyboard.press('Enter');
await expect(menu.getByRole('link')).toHaveCount(7);
await menu.getByRole('link',{name:'Usage & quality',exact:true}).click();
await page.locator('main [aria-busy=true]').waitFor({state:'hidden'});
await expect(menu).not.toHaveAttribute('open','');
await expect(page.getByRole('heading',{name:'Review queue',exact:true})).toBeVisible();
await expect(page.locator('#revision')).toHaveAttribute('aria-describedby','revision-hint');
const first=await page.getByRole('heading',{name:'Usage & quality',exact:true}).evaluate(e=>e.getBoundingClientRect().top);
if(first>=720)throw Error('Page title not in viewport');
await page.keyboard.press('Control+Home');
const fonts=await page.evaluate(()=>({body:getComputedStyle(document.body).fontFamily,title:getComputedStyle(document.querySelector('h1')).fontFamily}));
await fs.writeFile('../pipeline-hifi/qa/s06-responsive.json',JSON.stringify({date:new Date().toISOString(),checks:['keyboard opens mobile menu','seven destinations','destination collapses menu','loaded route content','field hint relation','title within720px'],titleTop:first,fonts},null,2));
await browser.close();console.log('6 responsive checks PASS');
