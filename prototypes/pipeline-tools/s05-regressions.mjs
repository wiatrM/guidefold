import {chromium} from '@playwright/test';
import {writeFile} from 'node:fs/promises';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1280,height:720},acceptDownloads:true});
const report={date:'2026-09-06',fixture:'Meridian',checks:[],errors:[]};
page.on('pageerror',e=>report.errors.push(e.message));
await page.goto('http://127.0.0.1:4320/proposals.html');
await page.getByRole('radio',{name:'Approve for export',exact:false}).check();
await page.getByLabel('Reason for this decision').fill('Fixture regression: exact imported source, scope and digest checked.');
await page.getByRole('button',{name:'Record decision (local)'}).click();
const download=page.waitForEvent('download');
await page.getByRole('button',{name:'Export SKILL.md'}).click();
await download;
await page.getByRole('button',{name:'Simulate Git sync'}).click();
report.checks.push({check:'stage-specific action',pass:await page.getByRole('link',{name:'Review publication evidence',exact:true}).count()===1});
const summary=page.getByText('Local simulation only · Context loaded: Unknown',{exact:true});
await page.evaluate(()=>window.scrollTo(0,0));
const bounds=await summary.boundingBox();
report.checks.push({check:'evidence above fold',pass:!!bounds&&bounds.y>=0&&bounds.y+bounds.height<=720,bounds});
report.checks.push({check:'source publication qualified',pass:(await page.locator('main').innerText()).includes('publication at import: not established')});
const digest=(await page.locator('section').filter({has:page.getByRole('heading',{name:'Decision and publication'})}).locator('dd').allTextContents())[1].trim();
await page.getByRole('link',{name:'Check usage evidence'}).click();
report.checks.push({check:'empty queue neutral heading',pass:await page.getByRole('heading',{name:'Review queue',exact:true}).count()===1});
const url=new URL(page.url());
report.checks.push({check:'skill/scope/revision context preserved',pass:url.searchParams.get('revision')===digest&&url.searchParams.get('scope')==='atlas.identity.turnstile'&&url.searchParams.get('skill').endsWith(':postgres-auth')});
report.checks.push({check:'observation form matches revision',pass:await page.getByLabel('Revision',{exact:true}).inputValue()===digest});
await writeFile('../pipeline-wireframes/qa/s05-regressions.json',JSON.stringify(report,null,2));
await browser.close();
console.log(JSON.stringify(report));
if(report.errors.length||report.checks.some(x=>!x.pass))process.exitCode=1;
